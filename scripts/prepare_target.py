"""Version-gated HP1 observer descriptors, derived from this installation."""
import hashlib
import json
import struct
import shutil
from inspect_pe import PE
from project_paths import inside, write_text

SYSTEM = inside('Harry Potter TM/System')
TARGETS = [
    ('Tick', 'Engine.dll', '?Tick@UGameEngine@@UAEXM@Z'),
    ('ComputeRenderCoords', 'Engine.dll', '?ComputeRenderCoords@FSceneNode@@QAEXAAVFVector@@AAVFRotator@@@Z'),
    ('DrawWorld', 'Render.dll', '?DrawWorld@URender@@UAEXPAUFSceneNode@@@Z'),
    ('OccludeFrame', 'Render.dll', '?OccludeFrame@URender@@QAEXPAUFSceneNode@@@Z'),
]


def implementation(pe, symbol):
    row = next(e for e in pe.exports() if e['name'] == symbol)
    start = pos = int(row['rva'], 16)
    for _ in range(4):
        off = pe.offset(pos)
        if pe.take(off, 1) != b'\xe9':
            return start, pos
        pos += 5 + struct.unpack('<i', pe.take(off + 1, 4))[0]
    raise ValueError('Unexpected export thunk chain')


def describe(module, symbol):
    data = (SYSTEM / module).read_bytes()
    pe = PE(data)
    start, entry = implementation(pe, symbol)
    if pe.take(pe.offset(entry), 5) != bytes.fromhex('558bec6aff'):
        raise ValueError('Unreviewed function prolog: ' + symbol)
    return pe, dict(module=module, export=symbol, export_rva=start, entry_rva=entry,
                    thunk=pe.take(pe.offset(start), 5).hex(), sha256=hashlib.sha256(data).hexdigest())


def verify_originals():
    manifest = json.loads(inside('config/target-fingerprint.json').read_text(encoding='utf-8-sig'))
    for row in manifest['files']:
        data = inside(row['path']).read_bytes()
        if len(data) != row['bytes'] or hashlib.sha256(data).hexdigest() != row['sha256']:
            raise ValueError('Original changed: ' + row['path'])
    return manifest


def prepare_lobby():
    """Independent local map package for the rendering-only entrance scene."""
    source=inside('Harry Potter TM/Maps/Lev_Tut1.unr')
    destination=inside('cache/lobby/HP1VRLobby.unr')
    destination.parent.mkdir(parents=True,exist_ok=True)
    expected=hashlib.sha256(source.read_bytes()).hexdigest()
    if destination.exists():
        if destination.stat().st_nlink!=1:raise ValueError('Hardlinked entrance background')
        if hashlib.sha256(destination.read_bytes()).hexdigest()==expected:return
    shutil.copyfile(source,destination)
    if hashlib.sha256(destination.read_bytes()).hexdigest()!=expected:raise ValueError('Entrance background copy differs')


def main():
    original = verify_originals()
    prepare_lobby()
    rows = []
    for label, module, symbol in TARGETS:
        _, row = describe(module, symbol)
        rows.append(dict(label=label, **row))
    pe, profile = describe('Core.dll', '?appUserDir@@YAPBGXZ')
    off = pe.offset(profile['entry_rva'])
    assert pe.take(off + 0x1b, 3) == bytes.fromhex('66833d')
    assert pe.take(off + 0x93, 1) == b'\xb8'
    cache = pe.u32(off + 0x1e)
    assert pe.u32(off + 0x94) == cache
    profile['cache_rva'] = cache - pe.image_base
    render = PE((SYSTEM / 'Render.dll').read_bytes())
    assert render.take(render.offset(0x20232), 12) == bytes.fromhex('8d4d188d550c51528bceff15')
    engine = PE((SYSTEM / 'Engine.dll').read_bytes())
    # The decoded implementation stores FCoords origin at frame + 0x34.
    assert b'\x8d\x43\x34' in engine.take(engine.offset(0x82f50), 0x350)
    hashes = {r['path'].split('/')[-1]: r['sha256'] for r in original['files']}
    def blob(x):
        return '{' + ','.join('0x' + x[i:i+2] for i in range(0, len(x), 2)) + '}'
    lines = ['// Generated by prepare_target.py from verified HP1 originals.', '#pragma once',
             'struct Target { const char* label; const wchar_t* module; unsigned long exportRva, entryRva; unsigned char thunk[5]; };',
             'static const Target kTargets[] = {']
    for r in rows:
        lines.append(' {"%s",L"%s",0x%x,0x%x,%s},' % (r['label'],r['module'],r['export_rva'],r['entry_rva'],blob(r['thunk'])))
    lines += ['};', 'static const unsigned char kProlog[5]={0x55,0x8b,0xec,0x6a,0xff};',
              'static const unsigned long kUserDirEntryRva=0x%x;' % profile['entry_rva'],
              'static const unsigned long kUserDirCacheRva=0x%x;' % profile['cache_rva'],
              'static const unsigned long kMasterCoordsReturnRva=0x20242;',
              'static const unsigned long kPositionCallerEbpOffset=12, kRotationCallerEbpOffset=24, kFrameCoordsOriginOffset=0x34;',
              'struct ModuleHash {const wchar_t* name;const char* sha;};', 'static const ModuleHash kHashes[]={']
    for name in ('HP.exe','Core.dll','Engine.dll','Render.dll','D3DDrv.dll','WinDrv.dll'):
        lines.append(' {L"%s","%s"},' % (name,hashes[name]))
    lines += ['};']
    write_text('src/observed_target.h','\n'.join(lines)+'\n',exclusive=False)
    write_text('config/observer-targets.json',json.dumps(dict(game='HP1',targets=rows,profile=profile),indent=2)+'\n',exclusive=False)
    native=[('tick','Engine.dll',TARGETS[0][2]),('coords','Engine.dll',TARGETS[1][2]),
        ('world','Render.dll',TARGETS[2][2]),
        ('create','Render.dll','?CreateMasterFrame@URender@@UAEPAUFSceneNode@@PAVUViewport@@VFVector@@VFRotator@@PAUFScreenBounds@@@Z'),
        ('finish','Render.dll','?FinishMasterFrame@URender@@UAEXXZ'),
        ('dispatch','Engine.dll','?ProcessEvent@AActor@@UAEXPAVUFunction@@PAX1@Z'),
        ('internal','Core.dll','?ProcessInternal@UObject@@QAEXAAUFFrame@@QAX@Z')]
    native.append(('menuprint','Engine.dll','?WrappedPrint@UCanvas@@AAAXW4ERenderStyle@@AAH1PAVUFont@@HPBG@Z'))
    native.append(('size','Engine.dll','?ComputeRenderSize@FSceneNode@@QAEXXZ'))
    native += [('mesh','Render.dll','?DrawMesh@URender@@QAEXPAUFSceneNode@@PAUFDynamicSprite@@PAVAActor@@ABVFCoords@@K@Z'),
               ('lodmesh','Render.dll','?DrawLodMesh@URender@@QAEXPAUFSceneNode@@PAUFDynamicSprite@@PAVAActor@@ABVFCoords@@K@Z')]
    native.append(('applyanim','Engine.dll','?ApplyAnim@USkeletalMesh@@ABEXPAVAActor@@PAUCFSkelHeader@1@_N@Z'))
    native += [('loadmap','Engine.dll','?LoadMap@UGameEngine@@UAEPAVULevel@@ABVFURL@@PAVUPendingLevel@@PBV?$TMap@VFString@@V1@@@AAVFString@@@Z'),
               ('destroy','Engine.dll','?Destroy@UGameEngine@@UAEXXZ'),
               ('destroyactor','Engine.dll','?DestroyActor@ULevel@@UAEHPAVAActor@@H@Z'),
               ('traceactors','Engine.dll','?execTraceActors@AActor@@QAEXAAUFFrame@@QAX@Z')]
    h=['#pragma once','struct NativeTarget {const char* key;const wchar_t* module;unsigned long rva;unsigned char prefix[5];};','static const NativeTarget kNativeTargets[]={']
    for key,module,symbol in native:
        p=PE((SYSTEM/module).read_bytes());_,entry=implementation(p,symbol)
        h.append(' {"%s",L"%s",0x%x,%s},' % (key,module,entry,blob(p.take(p.offset(entry),5).hex())))
    # HP1 clipped-string helper called by execDrawTextClipped at 8a3ed, cdecl 48 bytes.
    # HP1 DrawMesh: frame/sprite/actor/coords/flags at +8/+c/+10/+14/+18;
    # native call forwards them to DrawLodMesh, thiscall ret 20 bytes.
    assert render.take(render.offset(0xe943),3)==bytes.fromhex('8b7510')
    assert render.take(render.offset(0xe970),22)==bytes.fromhex('8b55188b4514528b550c508b4508565250e8b829ffff')
    assert render.take(render.offset(0xe996),3)==bytes.fromhex('c21400')
    # CreateChildFrame copies parent into +8 and Mirror argument +1c to +20.
    assert render.take(render.offset(0x204a2),3)==bytes.fromhex('397308')
    assert render.take(render.offset(0x20869),3)==bytes.fromhex('8b4d1c')
    assert render.take(render.offset(0x20874),3)==bytes.fromhex('894b20')
    assert render.take(render.offset(0x20a76),3)==bytes.fromhex('c22400')
    assert engine.take(engine.offset(0x8a3ed),5)==b'\xe8'+struct.pack('<i',0x88430-0x8a3ed-5)
    assert engine.take(engine.offset(0x8a3f2),3)==bytes.fromhex('83c430')
    assert engine.take(engine.offset(0x87c2d),3)==bytes.fromhex('8b7508')
    h.append(' {"menustring",L"Engine.dll",0x88430,%s},' % blob(engine.take(engine.offset(0x88430),5).hex()))
    p=PE((SYSTEM/'Core.dll').read_bytes())
    assert p.take(p.offset(0x420ab),5)==bytes.fromhex('e849f1fbff')
    assert p.take(p.offset(0x11f9),5)==b'\xe9'+struct.pack('<i',0x47c20-0x11f9-5)
    h+=[' {"property",L"Core.dll",0x47c20,%s},' % blob(p.take(p.offset(0x47c20),5).hex()),'};']
    assert render.take(render.offset(0x1d4fa),3)==bytes.fromhex('89462c')
    assert engine.take(engine.offset(0x91e2e),3)==bytes.fromhex('894754')
    assert engine.take(engine.offset(0x91e57),3)==bytes.fromhex('8b4f54')
    # HP1 ApplyAnim: actor at +8, optional header at +c (null loads mesh header),
    # physics-only boolean at +10; callee releases 12 bytes. HP2 RVA differs.
    assert engine.take(engine.offset(0x11b730),3)==bytes.fromhex('8b7508')
    assert engine.take(engine.offset(0x11b8f2),3)==bytes.fromhex('8a4510')
    assert engine.take(engine.offset(0x11bb2d),3)==bytes.fromhex('8b450c')
    assert engine.take(engine.offset(0x11d417),3)==bytes.fromhex('c20c00')
    # HP1 DestroyActor: this=level, actor at +8, netForce +c, returns int; ret 8.
    assert engine.take(engine.offset(0xa6fbd),3)==bytes.fromhex('8b7508')
    assert engine.take(engine.offset(0xa7039),3)==bytes.fromhex('397d0c')
    assert engine.take(engine.offset(0xa7057),3)==bytes.fromhex('c20800')
    h+=['static const unsigned kRenderEngineOffset=0x2c,kEngineAudioOffset=0x54;']
    write_text('src/hp1_native_target.h','\n'.join(h)+'\n',exclusive=False)
    print('HP1 originals and derived observer targets verified.')


if __name__ == '__main__':
    main()
